-- CRUD DE PELICULAS Y SERIES

CREATE DATABASE IF NOT EXISTS cine_db;
USE cine_db;

DROP TABLE IF EXISTS peliculas;

CREATE TABLE IF NOT EXISTS peliculas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    tipo ENUM('pelicula', 'serie', 'documental') NOT NULL DEFAULT 'pelicula',
    director VARCHAR(255) NOT NULL,
    anio_estreno INT NOT NULL,
    duracion_min INT DEFAULT 120,
    genero VARCHAR(100) NOT NULL,
    calificacion DECIMAL(3,1) DEFAULT 8.5,
    sinopsis TEXT,
    poster_url TEXT,
    banner_url TEXT,
    trailer_url TEXT,
    disponible BOOLEAN DEFAULT TRUE,
    destacado BOOLEAN DEFAULT FALSE,
    temporadas INT DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

